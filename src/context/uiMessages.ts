export function translateUi(text: string, locale: "en" | "hi"): string {
  if (locale === "en") return text
  const trimmed = text.trim()
  const translated = hindiUi[trimmed] || hindiUi[trimmed.toLowerCase()]
  return translated ? text.replace(trimmed, () => translated) : text
}
